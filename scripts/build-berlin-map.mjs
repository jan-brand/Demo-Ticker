// Builds src/frontend/berlin-map.js from the official district boundaries (GeoJSON, lon/lat).
// The map is drawn as plain SVG, so no map tiles or third-party servers are involved at runtime.
//
// Usage: node scripts/build-berlin-map.mjs [path-or-url-to-geojson]
import { readFile, writeFile } from 'node:fs/promises';
import { fileURLToPath } from 'node:url';

const SOURCE_URL = 'https://tsb-opendata.s3.eu-central-1.amazonaws.com/bezirksgrenzen/bezirksgrenzen.geojson';
const input = process.argv[2] ?? SOURCE_URL;
const TOLERANCE_DEG = 0.0004; // about 30 to 45 m, invisible at city scale
const WIDTH = 1000;

const text = /^https?:/.test(input)
  ? await (await fetch(input)).text()
  : await readFile(input, 'utf8');
const geojson = JSON.parse(text);

const polygonsOf = (geometry) => (geometry.type === 'Polygon' ? [geometry.coordinates] : geometry.coordinates);

// Douglas-Peucker on lon/lat, iterative to survive long rings.
function simplify(points, tolerance) {
  if (points.length < 4) return points;
  const keep = new Uint8Array(points.length);
  keep[0] = keep[points.length - 1] = 1;
  const stack = [[0, points.length - 1]];
  const sq = tolerance * tolerance;
  while (stack.length) {
    const [first, last] = stack.pop();
    const [x1, y1] = points[first];
    const [x2, y2] = points[last];
    const dx = x2 - x1;
    const dy = y2 - y1;
    const len = dx * dx + dy * dy;
    let worst = 0;
    let index = -1;
    for (let i = first + 1; i < last; i += 1) {
      const [x, y] = points[i];
      const t = len ? Math.max(0, Math.min(1, ((x - x1) * dx + (y - y1) * dy) / len)) : 0;
      const d = (x - (x1 + t * dx)) ** 2 + (y - (y1 + t * dy)) ** 2;
      if (d > worst) { worst = d; index = i; }
    }
    if (worst > sq && index > 0) {
      keep[index] = 1;
      stack.push([first, index], [index, last]);
    }
  }
  return points.filter((_, i) => keep[i]);
}

const features = geojson.features.map((feature) => ({
  name: feature.properties.Gemeinde_name,
  rings: polygonsOf(feature.geometry).map((polygon) => simplify(polygon[0], TOLERANCE_DEG)).filter((ring) => ring.length >= 4),
}));

const all = features.flatMap((f) => f.rings.flat());
const lons = all.map((p) => p[0]);
const lats = all.map((p) => p[1]);
const lonMin = Math.min(...lons);
const lonMax = Math.max(...lons);
const latMin = Math.min(...lats);
const latMax = Math.max(...lats);
const cosLat0 = Math.cos((((latMin + latMax) / 2) * Math.PI) / 180);
const scale = WIDTH / ((lonMax - lonMin) * cosLat0);
const height = Math.round((latMax - latMin) * scale);

const project = ([lon, lat]) => [(lon - lonMin) * cosLat0 * scale, (latMax - lat) * scale];
const round = (value) => Math.round(value * 10) / 10;

function areaCentroid(ring) {
  let area = 0;
  let cx = 0;
  let cy = 0;
  for (let i = 0; i < ring.length - 1; i += 1) {
    const [x0, y0] = ring[i];
    const [x1, y1] = ring[i + 1];
    const cross = x0 * y1 - x1 * y0;
    area += cross;
    cx += (x0 + x1) * cross;
    cy += (y0 + y1) * cross;
  }
  return { area: Math.abs(area / 2), x: cx / (3 * area), y: cy / (3 * area) };
}

const districts = features.map(({ name, rings }) => {
  const projected = rings.map((ring) => ring.map(project));
  const largest = projected.map(areaCentroid).sort((a, b) => b.area - a.area)[0];
  const d = projected.map((ring) => `M${ring.map(([x, y]) => `${round(x)} ${round(y)}`).join('L')}Z`).join('');
  return { name, d, labelX: round(largest.x), labelY: round(largest.y) };
});

const module = {
  source: 'ALKIS Berlin Bezirke, Senatsverwaltung für Stadtentwicklung, Bauen und Wohnen (Geoportal Berlin), Datenlizenz Deutschland - Zero - Version 2.0; Aufbereitung als GeoJSON: Technologiestiftung Berlin',
  lonMin, latMax, cosLat0, scale, width: WIDTH, height, districts,
};

const target = fileURLToPath(new URL('../src/frontend/berlin-map.js', import.meta.url));
await writeFile(target, `// Generated by scripts/build-berlin-map.mjs, do not edit.\nexport default ${JSON.stringify(module)};\n`);
const size = JSON.stringify(module).length;
console.log(`${districts.length} Bezirke, ${all.length} Punkte, ${(size / 1024).toFixed(1)} KB -> src/frontend/berlin-map.js`);
